def compare_csv_files(file1_path, file2_path, tolerance=1e-6):
    """Compare two CSV files, checking for numeric differences."""
    df1 = pd.read_csv(file1_path)
    df2 = pd.read_csv(file2_path)

    # Basic checks
    assert df1.shape == df2.shape, \
        f"Shape mismatch between {os.path.basename(file1_path)} and " \
        f"{os.path.basename(file2_path)}"
    assert df1.columns.equals(df2.columns), \
        f"Column mismatch in {os.path.basename(file1_path)}"

    # Sort to ensure proper comparison
    sort_cols = ["End use", "CDIV"]
    df1 = df1.sort_values(by=sort_cols).reset_index(drop=True)
    df2 = df2.sort_values(by=sort_cols).reset_index(drop=True)

    # Compare non-numeric columns
    non_numeric_cols = df1.select_dtypes(exclude=np.number).columns
    pd.testing.assert_frame_equal(df1[non_numeric_cols], df2[non_numeric_cols])

    # Compare numeric columns with tolerance
    numeric_cols = df1.select_dtypes(include=np.number).columns
    pd.testing.assert_frame_equal(
        df1[numeric_cols],
        df2[numeric_cols],
        check_exact=False,
        atol=tolerance,
        rtol=tolerance
    )

