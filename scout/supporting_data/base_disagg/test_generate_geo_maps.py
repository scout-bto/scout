NON_STATE_COLS = {"Technology", "End use", "CDIV", "Total"}


def _state_geo_csv_paths():
    """Locate every Cdiv/State-geography output file (across fuels, the
    Stock variant, and the tech-level variant), skipping the Cdiv/EMM
    files -- those share the same CDIV row label but their columns are
    EMM regions, not states.
    """
    paths = []
    for subdir in ("end_use", "technology"):
        pattern = os.path.join(OUTPUT_DIR, f"*_{subdir}", "*_Cdiv_State_*.csv")
        paths.extend(glob.glob(pattern))
    return sorted(paths)


def test_state_shares_sum_to_one(run_generation_script):
    """Each row disaggregates a Census-division-level value out to its
    member states, so the state-column shares in a given row (one
    End use, or one Technology/End use, within one CDIV) must sum to 1.
    """
    csv_paths = _state_geo_csv_paths()
    assert csv_paths, (
        f"No Cdiv/State output files found under {OUTPUT_DIR} to check."
    )

    for csv_path in csv_paths:
        df = pd.read_csv(csv_path)
        state_cols = [c for c in df.columns if c not in NON_STATE_COLS]
        row_sums = df[state_cols].sum(axis=1)

        # A row with every state column at 0 means there was no data at
        # all for that End use/CDIV(/Technology) combination -- a real
        # degenerate case (e.g. a fuel with no consumption in that
        # division), not a disaggregation bug -- so it's excluded rather
        # than asserted to sum to 1.
        nonzero = row_sums[row_sums.abs() > 1e-9]
        bad = nonzero[(nonzero - 1).abs() > 1e-6]

        id_cols = [c for c in ("Technology", "End use", "CDIV")
                   if c in df.columns]
        assert bad.empty, (
            f"{os.path.basename(csv_path)}: state shares do not sum to "
            f"1 for these rows:\n{df.loc[bad.index, id_cols].assign(sum=bad)}"
        )


def test_gap_row_present_and_sums_to_one(run_generation_script):
    """The ComStock "gap" row (see generate_geo_maps.process_gap_end_use)
    should be present in the commercial electricity outputs -- both
    end-use-level and technology-level, EMM and State, energy and stock --
    and sum to 1 across regions per CDIV, just like every other row. Real
    gap SDR data only covers electricity and has no per-technology
    breakdown, so the technology-level "gap" row is tagged Technology ==
    "all"; no other fuel's files should carry a "gap" row.
    """
    elec_paths = glob.glob(os.path.join(
        OUTPUT_DIR, "*_end_use", "Com_Cdiv_*_electricity*.csv"))
    elec_paths += glob.glob(os.path.join(
        OUTPUT_DIR, "*_technology", "Com_Cdiv_*_electricity*.csv"))
    assert elec_paths, "No commercial electricity output files found."

    for path in elec_paths:
        df = pd.read_csv(path)
        gap_rows = df[df["End use"] == "gap"]
        assert not gap_rows.empty, f"No 'gap' row found in {path}"
        if "Technology" in df.columns:
            assert (gap_rows["Technology"] == "all").all(), (
                f"'gap' row(s) in {path} should be tagged Technology == 'all'")

        region_cols = [c for c in df.columns if c not in NON_STATE_COLS]
        row_sums = gap_rows[region_cols].sum(axis=1)
        nonzero = row_sums[row_sums.abs() > 1e-9]
        bad = nonzero[(nonzero - 1).abs() > 1e-6]
        assert bad.empty, f"'gap' row shares don't sum to 1 in {path}:\n{bad}"

    other_paths = [
        p for p in (
            glob.glob(os.path.join(OUTPUT_DIR, "*_end_use", "Com_Cdiv_*.csv")) +
            glob.glob(os.path.join(OUTPUT_DIR, "*_technology", "Com_Cdiv_*.csv")))
        if "electricity" not in os.path.basename(p)]
    for path in other_paths:
        df = pd.read_csv(path)
        assert (df["End use"] != "gap").all(), f"Unexpected 'gap' row found in {path}"


